"""Emit the reconstructed racial Shelter routes from their reviewed catalog.

Placement clearance/traversal is checked by AC2.Data.StarterClearance against
the client's cooked native collision, not asserted by this authoring script.
"""
import hashlib
import json
from pathlib import Path

CONTENT = Path(__file__).resolve().parents[1] / 'content'


def generate():
    source = CONTENT / 'starter-areas-v1.json'
    data = json.loads(source.read_text(encoding='utf8'))
    assert data['version'] == 1
    existing = {line.split('\t')[0] for line in (CONTENT / 'training-world.tsv').read_text().splitlines()[1:]}
    world = ['pyrealium-world-v3', '# Generated by author_starters.py; see starter-areas-v1.json for provenance.']
    routes = ['pyrealium-portal-routes-v1']
    seen = set()
    for area in data['areas']:
        for room in (area, area['vault']):
            for row in room['actors']:
                assert row['id'] not in seen
                seen.add(row['id'])
                if row['id'] not in existing:
                    world.append('\t'.join([row['id'], f"{row['entity']:08x}", f"{row['visual']:08x}",
                        f"{row['cell']:08x}", *[f'{v:.8f}' for v in row['position']],
                        *[f'{v:.9f}' for v in row.get('orientation', [1, 0, 0, 0])], str(row.get('scale', '-'))]))
                destination = (area['vault']['start'] if row['role'] == 'menhir-portal'
                               else area['overworld'] if row['role'] in ('shard', 'shortcut-portal') else None)
                if destination:
                    routes.append('\t'.join([row['id'], f"{row['entity']:08x}", f"{row['cell']:08x}",
                        *[f'{v:.8f}' for v in row['position']], f"{destination['cell']:08x}",
                        *[f'{v:.8f}' for v in destination['position']], '0', '1']))
    for name, lines in [('starter-world-v1.tsv', world), ('starter-routes-v1.tsv', routes)]:
        (CONTENT / name).write_text('\n'.join(lines) + '\n', encoding='utf8', newline='\n')
    def sha(path):
        return hashlib.sha256(path.read_bytes().replace(b'\r\n', b'\n')).hexdigest()
    report = dict(version=1, source_sha256=sha(source),
                  manifest_sha256=sha(CONTENT/'starter-world-v1.tsv'),
                  routes_sha256=sha(CONTENT/'starter-routes-v1.tsv'),
                  actors=len(world)-2, routes=len(routes)-1,
                  validation='AC2.Data.StarterClearance; UE cooked DAT collision and capsule clearance',
                  policy=data['policy'])
    (CONTENT/'starter-world-v1.report.json').write_text(json.dumps(report, indent=2)+'\n', encoding='utf8', newline='\n')


if __name__ == '__main__':
    generate()
